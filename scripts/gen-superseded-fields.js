// scripts/gen-superseded-fields.js
// Lists every value the items pack has ever shipped for a refreshable field of a move, a treasure or
// a piece of gear, and writes module/migration/data/superseded-move-fields.js: what tells
// migration/move-refresh.js a held copy nobody edited (its value is one the pack shipped) from one
// a GM did (it is not). Reads the git history, so it needs a full clone, not a shallow one.
//
// Run with: npm run gen:superseded            (writes the data module)
//           npm run gen:superseded -- --report (also prints, per entry, which fields have former values)
//
// Rerun before every release, after any change to the pack sources. tests/migration/
// superseded-data-fresh.test.js fails when the pack and the generated data disagree.

import { execFileSync, spawnSync } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { supersededValues, bestiarySuperseded } from "./lib/superseded-history.js";
import { MONSTER_PATHS, MONSTER_MOVE_PATHS, monsterFingerprint } from "../module/migration/bestiary-refresh.js";
import { SUPERSEDED_FORMAT } from "../module/migration/superseded-values.js";
import { CARDS_FORMAT, improvementCardsIn, improvementHash, cardKey } from "../module/migration/improvement-refresh.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const current = path.join(root, "packs", "src", "stonetop-items");
const out = path.join(root, "module", "migration", "data", "superseded-move-fields.js");
const cardsOut = path.join(root, "module", "migration", "data", "superseded-improvement-cards.js");
const bestiaryOut = path.join(root, "module", "migration", "data", "superseded-bestiary.js");
const BESTIARY_DIRS = ["packs/src/stonetop-bestiary"];

// Where a Book II steading-improvement card has lived: baked into the journal packs' page HTML.
export const CARD_DIRS = ["stonetop-locations", "stonetop-lore", "stonetop-journals", "reference-journals", "setting-overview"]
	.map(d => `packs/src/${d}`);

// Where a move or a piece of gear has lived in the pack sources: the consolidated items pack, and the
// per-kind directories it was assembled from. Arcana are left out: they were moves once, but live in
// a pack of their own now, and a held arcanum is not refreshed from this one.
const HISTORY_DIRS = [
	"stonetop-items", "playbook-moves", "basic-moves", "expedition-moves", "homefront-moves",
	"special-moves", "follower-moves", "post-death-moves", "inventory-items",
].map(d => `packs/src/${d}`);

const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

async function readTree(dir) {
	const docs = [];
	for (const e of await fs.readdir(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) docs.push(...await readTree(p));
		else if (e.name.endsWith(".json") && !e.name.startsWith("_")) docs.push(JSON.parse(await fs.readFile(p, "utf8")));
	}
	return docs;
}

/** Every blob any commit wrote under `dirs`. */
function historyBlobs(dirs) {
	const raw = git("log", "--raw", "--no-renames", "--no-abbrev", "--format=", "--", ...dirs);
	const blobs = new Set();
	for (const line of raw.split("\n")) {
		const m = /^:\d+ \d+ [0-9a-f]+ ([0-9a-f]+) [AM]\t(.+\.json)$/.exec(line);
		if (m && !/\/_folders\//.test(m[2])) blobs.add(m[1]);
	}
	return [...blobs];
}

/** The blobs' contents, through one `git cat-file --batch`. */
function readBlobs(shas) {
	const res = spawnSync("git", ["cat-file", "--batch"], { cwd: root, input: shas.join("\n") + "\n", maxBuffer: 1024 * 1024 * 1024 });
	if (res.status !== 0) throw new Error(`git cat-file failed: ${res.stderr}`);
	const buf = res.stdout;
	const docs = [];
	let at = 0;
	while (at < buf.length) {
		const nl = buf.indexOf(10, at);
		const [, kind, size] = buf.subarray(at, nl).toString("utf8").split(" ");
		at = nl + 1;
		if (kind !== "blob") continue;
		const n = Number(size);
		const text = buf.subarray(at, at + n).toString("utf8");
		at += n + 1;
		try { docs.push(JSON.parse(text)); } catch { /* not JSON at that commit: nothing to list */ }
	}
	return docs;
}

async function main() {
	if (git("rev-parse", "--is-shallow-repository").trim() === "true") {
		throw new Error("This is a shallow clone, so the pack's history is incomplete. Fetch it whole (git fetch --unshallow) first.");
	}
	const entries = (await readTree(current)).filter(d => d.type === "move");
	const shas = historyBlobs(HISTORY_DIRS);
	const history = readBlobs(shas);
	const { superseded, fingerprints, orphans } = supersededValues(history, entries);

	const names = new Map(entries.map(e => [e._id, `${e.name}${e.system?.playbook ? ` (${e.system.playbook})` : ""}`]));
	const lines = [
		"// GENERATED by scripts/gen-superseded-fields.js. Do not edit: run `npm run gen:superseded`.",
		"// Every former value of each refreshable field of an items-pack entry, as a hash",
		"// (module/migration/superseded-values.js), by pack _id. See migration/move-refresh.js.",
		"",
		`export const SUPERSEDED_FORMAT = ${SUPERSEDED_FORMAT};`,
		"",
		"export const SUPERSEDED = {",
		...Object.entries(superseded).map(([id, paths]) => `\t${JSON.stringify(id)}: ${JSON.stringify(paths)}, // ${names.get(id)}`),
		"};",
		"",
		"// What the pack held when this was generated, so a sweep can tell data older than the pack.",
		"export const CURRENT_FINGERPRINTS = {",
		...Object.entries(fingerprints).map(([id, hash]) => `\t${JSON.stringify(id)}: ${JSON.stringify(hash)},`),
		"};",
		"",
	];
	await fs.mkdir(path.dirname(out), { recursive: true });
	await fs.writeFile(out, lines.join("\n"), "utf8");
	const listed = Object.keys(superseded).length;
	console.log(`Read ${history.length} versions (${shas.length} blobs) against ${entries.length} entries: ${listed} have former values.`);
	console.log(`Wrote ${path.relative(root, out)}.`);

	await writeCards();
	await writeBestiary();

	if (process.argv.includes("--report")) {
		for (const [id, paths] of Object.entries(superseded)) {
			console.log(`${names.get(id)}: ${Object.entries(paths).map(([p, h]) => `${p}×${h.length}`).join(", ")}`);
		}
		console.log(`\nOrphans (in the history, no current entry): ${orphans.join("; ") || "none"}`);
	}
}

/** The Book II improvement cards: each current card, and the hash of every version it shipped as before. */
async function writeCards() {
	const current = new Map();
	for (const dir of CARD_DIRS) {
		const full = path.join(root, dir);
		const docs = await readTree(full).catch(() => []);
		for (const card of docs.flatMap(improvementCardsIn)) if (!current.has(cardKey(card))) current.set(cardKey(card), card);
	}
	const former = new Map([...current.keys()].map(k => [k, new Set()]));
	for (const card of readBlobs(historyBlobs(CARD_DIRS)).flatMap(improvementCardsIn)) former.get(cardKey(card))?.add(improvementHash(card));
	const cards = {};
	for (const [key, def] of [...current].sort(([a], [b]) => a.localeCompare(b))) {
		const now = improvementHash(def);
		cards[key] = { def, former: [...former.get(key)].filter(h => h !== now).sort() };
	}
	const lines = [
		"// GENERATED by scripts/gen-superseded-fields.js. Do not edit: run `npm run gen:superseded`.",
		"// Each Book II steading-improvement card the journal packs ship, by name (case-blind), with the",
		"// hash of every earlier version of it (migration/improvement-refresh.js).",
		"",
		`export const CARDS_FORMAT = ${CARDS_FORMAT};`,
		"",
		`export const IMPROVEMENT_CARDS = ${JSON.stringify(cards, null, "\t")};`,
		"",
	];
	await fs.writeFile(cardsOut, lines.join("\n"), "utf8");
	console.log(`Wrote ${path.relative(root, cardsOut)}: ${current.size} cards, ${Object.values(cards).filter(c => c.former.length).length} with earlier versions.`);
}

/** The seeded monsters: every earlier value of each stat-block field and each of its moves' fields. */
async function writeBestiary() {
	const current = (await readTree(path.join(root, BESTIARY_DIRS[0]))).filter(d => d.type && d._id && Array.isArray(d.items));
	const history = readBlobs(historyBlobs(BESTIARY_DIRS));
	const superseded = bestiarySuperseded(history, current, { actor: MONSTER_PATHS, move: MONSTER_MOVE_PATHS });
	const names = new Map(current.map(e => [e._id, e.name]));
	const lines = [
		"// GENERATED by scripts/gen-superseded-fields.js. Do not edit: run `npm run gen:superseded`.",
		"// Every earlier value of each refreshed field of a bestiary stat block and its moves, as a hash,",
		"// by pack _id (migration/bestiary-refresh.js).",
		"",
		`export const SUPERSEDED_FORMAT = ${SUPERSEDED_FORMAT};`,
		"",
		"export const SUPERSEDED_BESTIARY = {",
		...Object.entries(superseded).map(([id, v]) => `\t${JSON.stringify(id)}: ${JSON.stringify(v)}, // ${names.get(id)}`),
		"};",
		"",
		"// What the pack held when this was generated, so data older than the pack is caught.",
		"export const BESTIARY_FINGERPRINTS = {",
		...[...current].sort((a, b) => a._id.localeCompare(b._id)).map(e => `\t${JSON.stringify(e._id)}: ${JSON.stringify(monsterFingerprint(e))},`),
		"};",
		"",
	];
	await fs.writeFile(bestiaryOut, lines.join("\n"), "utf8");
	console.log(`Wrote ${path.relative(root, bestiaryOut)}: ${Object.keys(superseded).length} of ${current.length} stat blocks have earlier values (${history.length} versions read).`);
}

main().catch(err => { console.error(err.message ?? err); process.exit(1); });
